#!/usr/bin/env node

/**
 * Builds src/constants/licenses.ts: the open-source packages the app is built with and their
 * license texts, shown under Settings → Personal Data & Privacy → Open-Source Licenses (src/app/licenses.tsx).
 * It lists the packages in "dependencies" of package.json, with the version that is installed.
 * Run after adding, removing or upgrading a dependency: `npm run licenses`.
 */

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const outFile = path.join(root, 'src', 'constants', 'licenses.ts');
const LICENSE_FILE = /^(licen[sc]e|copying)(\.(md|txt))?$/i;

const { dependencies } = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));

function licenseText(dir) {
  const file = fs
    .readdirSync(dir)
    .filter((name) => LICENSE_FILE.test(name))
    .sort()[0];
  if (!file) return '';
  return fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').trim();
}

const repository = (manifest) =>
  (typeof manifest.repository === 'string' ? manifest.repository : (manifest.repository?.url ?? ''))
    .replace(/^git\+/, '')
    .replace(/\.git$/, '');

const found = Object.keys(dependencies)
  .sort()
  .map((name) => {
    const dir = path.join(root, 'node_modules', name);
    const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
    const license = typeof manifest.license === 'string' ? manifest.license : (manifest.license?.type ?? '');
    return { name, version: manifest.version, license, text: licenseText(dir), repository: repository(manifest) };
  });

// A package published from a monorepo without its own license file is under the repository's license:
// take the text from another package of the same repository.
const byRepository = new Map();
for (const entry of found) {
  if (entry.text && entry.repository && !byRepository.has(entry.repository)) byRepository.set(entry.repository, entry.text);
}

const texts = [];
const packages = [];
const missing = [];
for (const { name, version, license, text: own, repository: repo } of found) {
  const text = own || byRepository.get(repo) || '';
  if (!text || !license) missing.push(name);
  let index = texts.indexOf(text);
  if (index === -1) index = texts.push(text) - 1;
  packages.push({ name, version, license, text: index });
}

fs.writeFileSync(
  outFile,
  `// Generated by scripts/build-licenses.js (\`npm run licenses\`). Do not edit by hand.

export interface OpenSourcePackage {
  name: string;
  version: string;
  /** SPDX identifier from the package's own package.json. */
  license: string;
  /** Index into \`LICENSE_TEXTS\`; packages with the same text share one entry. */
  text: number;
}

export const OPEN_SOURCE_PACKAGES: readonly OpenSourcePackage[] = ${JSON.stringify(packages, null, 2)};

export const LICENSE_TEXTS: readonly string[] = ${JSON.stringify(texts, null, 2)};
`
);

console.log(`Wrote ${packages.length} packages and ${texts.length} license texts to ${path.relative(root, outFile)}`);
if (missing.length > 0) {
  console.error(`No license name or license file found for: ${missing.join(', ')}`);
  process.exit(1);
}
